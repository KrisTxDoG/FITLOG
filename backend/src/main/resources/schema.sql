CREATE TABLE IF NOT EXISTS workouts (
 id VARCHAR(36) PRIMARY KEY,
 title VARCHAR(80) NOT NULL,
 workout_date DATE NOT NULL,
 duration_minutes INT NOT NULL CHECK(duration_minutes BETWEEN 1 AND 600),
 notes VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS custom_exercises (
 id VARCHAR(40) PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 muscle VARCHAR(40) NOT NULL,
 equipment VARCHAR(60) NOT NULL,
 rest_seconds INT NOT NULL CHECK(rest_seconds BETWEEN 5 AND 900)
);
ALTER TABLE workouts ADD COLUMN IF NOT EXISTS created_order BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE TABLE IF NOT EXISTS workout_sets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workout_id VARCHAR(36) NOT NULL REFERENCES workouts(id) ON DELETE CASCADE,
 exercise_id VARCHAR(40) NOT NULL,
 reps INT NOT NULL CHECK(reps BETWEEN 1 AND 1000),
 weight DECIMAL(7,2) NOT NULL CHECK(weight BETWEEN 0 AND 1000)
);
ALTER TABLE workout_sets ADD COLUMN IF NOT EXISTS completed BOOLEAN DEFAULT FALSE NOT NULL;
CREATE TABLE IF NOT EXISTS templates (
 id VARCHAR(36) PRIMARY KEY,
 title VARCHAR(80) NOT NULL,
 duration_minutes INT NOT NULL CHECK(duration_minutes BETWEEN 1 AND 600),
 notes VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS template_sets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 template_id VARCHAR(36) NOT NULL REFERENCES templates(id) ON DELETE CASCADE,
 exercise_id VARCHAR(40) NOT NULL,
 reps INT NOT NULL CHECK(reps BETWEEN 1 AND 1000),
 weight DECIMAL(7,2) NOT NULL CHECK(weight BETWEEN 0 AND 1000)
);

CREATE TABLE IF NOT EXISTS members(id VARCHAR(36) PRIMARY KEY,email VARCHAR(254) NOT NULL UNIQUE,display_name VARCHAR(60) NOT NULL,password_hash VARCHAR(100) NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL);
CREATE TABLE IF NOT EXISTS membership_state(id INT PRIMARY KEY,legacy_claimed BOOLEAN NOT NULL);
INSERT INTO membership_state(id,legacy_claimed) SELECT 1,FALSE WHERE NOT EXISTS(SELECT 1 FROM membership_state WHERE id=1);
ALTER TABLE workouts ADD COLUMN IF NOT EXISTS owner_id VARCHAR(36) REFERENCES members(id);
CREATE INDEX IF NOT EXISTS idx_workouts_owner ON workouts(owner_id);
ALTER TABLE templates ADD COLUMN IF NOT EXISTS owner_id VARCHAR(36) REFERENCES members(id);
CREATE INDEX IF NOT EXISTS idx_templates_owner ON templates(owner_id);
ALTER TABLE custom_exercises ADD COLUMN IF NOT EXISTS owner_id VARCHAR(36) REFERENCES members(id);
CREATE INDEX IF NOT EXISTS idx_custom_exercises_owner ON custom_exercises(owner_id);
ALTER TABLE members ADD COLUMN IF NOT EXISTS weekly_goal INT DEFAULT 3 NOT NULL CHECK(weekly_goal BETWEEN 1 AND 7);
CREATE TABLE IF NOT EXISTS scheduled_workouts (
 id VARCHAR(36) PRIMARY KEY,
 owner_id VARCHAR(36) NOT NULL REFERENCES members(id),
 template_id VARCHAR(36) NOT NULL REFERENCES templates(id) ON DELETE CASCADE,
 scheduled_date DATE NOT NULL,
 UNIQUE(owner_id,template_id,scheduled_date)
);
CREATE INDEX IF NOT EXISTS idx_schedule_owner ON scheduled_workouts(owner_id);

